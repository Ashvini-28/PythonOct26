#1. decimal form 0-9

x=10
print("x=",x)
print(type(x))


#2. binary form prefix 0b or 0B allowed digit 0 and 1
x=0b1010
print("x=",x)
print(type(x))

#3. octal form prefix 0o or 0O allowed digit 0-7
x=0o12
print("x=",x)
print(type(x))

#4. hexadecimal form prefix 0x or 0X allowed digit 0-9 and a-f or A-F
x=0xA
print("x=",x)
print(type(x))

